# Prints internal/controller/assets/dashboard-reference-rows.sql from a dashboard control database
# (operator#378): every row of subscription_plans, stripe_addon_prices and llms, all columns, with
# the Stripe price ID columns removed (those are per stack, spec.components.controlDB.stripePrices).
#
# Usage: hack/export-dashboard-reference-rows.sh <source label> > internal/controller/assets/dashboard-reference-rows.sql
# with DATABASE_URL set to the source database (Prod 1). The session is read-only
# (default_transaction_read_only) and runs SELECT only.
set -eu
label=${1:?usage: $0 <source label, e.g. "Prod 1 PlanetScale, read by <name>">}
: "${DATABASE_URL:?DATABASE_URL must name the source database}"

cat <<EOF
-- Reference rows for dashboard-reference-data.sql (operator#378). Generated by
-- hack/export-dashboard-reference-rows.sh with a read-only SELECT; do not edit by hand.
-- Source: $label, $(date -u +%Y-%m-%dT%H:%MZ).
-- Every column of every row, IDs and timestamps preserved, Stripe price IDs removed.
EOF
PGOPTIONS='-c default_transaction_read_only=on' psql "$DATABASE_URL" -X -q -At -v ON_ERROR_STOP=1 <<'SQL'
BEGIN READ ONLY;
SELECT format('INSERT INTO reference_subscription_plans SELECT * FROM json_populate_record(NULL::reference_subscription_plans, %L);',
  to_jsonb(p) - 'stripe_price_id_monthly' - 'stripe_price_id_yearly')
FROM subscription_plans p ORDER BY p.id;
SELECT format('INSERT INTO reference_stripe_addon_prices SELECT * FROM json_populate_record(NULL::reference_stripe_addon_prices, %L);',
  to_jsonb(a) - 'stripe_price_id')
FROM stripe_addon_prices a ORDER BY a.id;
SELECT format('INSERT INTO reference_llms SELECT * FROM json_populate_record(NULL::reference_llms, %L);', to_jsonb(l))
FROM llms l ORDER BY l.id;
ROLLBACK;
SQL
